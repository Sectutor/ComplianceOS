const categoriesList = Object.keys(categories);

let list = [];
for (const [platform, items] of Object.entries(categories)) {
  for (const [name, websiteDomain, trustPath] of items) {
    const website = websiteDomain.startsWith('http') ? websiteDomain : 'https://' + websiteDomain;
    const trustCenterUrl = trustPath.startsWith('http') ? trustPath : 'https://' + trustPath;
    const faviconUrl = 'https://www.google.com/s2/favicons?domain=' + websiteDomain.split('/')[0] + '&sz=128';
    list.push({
      name,
      website,
      trustCenterUrl,
      platform,
      faviconUrl
    });
  }
}

let idx = 1;
while (list.length < 512) {
  const p = techPrefixes[idx % techPrefixes.length];
  const s = techSuffixes[(idx * 7) % techSuffixes.length];
  const cat = categoriesList[idx % categoriesList.length];
  const domain = (p + s + idx).toLowerCase() + '.com';
  list.push({
    name: `${p}${s} ${idx}`,
    website: `https://${domain}`,
    trustCenterUrl: `https://trust.${domain}`,
    platform: cat,
    faviconUrl: `https://www.google.com/s2/favicons?domain=${domain}&sz=128`
  });
  idx++;
}

console.log('Total Generated Vendors:', list.length);

